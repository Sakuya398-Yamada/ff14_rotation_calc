#!/usr/bin/env bash
# knowledge-board.sh — read the workflow knowledge board Issue a little at a time, and append a
# "✅ Issue #N" marker to a comment and check that it was saved as sent.
#
# Usage: knowledge-board.sh <command> [--cached]
#   open              unresolved insights, one line each
#   grep <pattern>    matching lines only (case-insensitive extended regex; an invalid regex
#                     is matched as a plain string)
#   show <id>         the whole body of one comment
#   mark <id> "<marker>"
#                     append a marker line ("✅ Issue #N ..." or "✅ Issue owner/repo#N ...") to
#                     any comment of this repository, then fetch it again and compare
#   --cached          open / grep / show reuse the comments saved by the last fetch instead of
#                     calling gh again
#
# Reading the board with the GitHub MCP issue_read (get_comments) puts every comment and its
# metadata into the conversation. This script keeps them in a file under the git directory and
# prints only what was asked for. The board's number is read from the "知見ボードIssue" section of
# .claude/rules/workflow-feedback.md, so it is written in one place.
#
# Needs only bash (3.2+) and gh: JSON is processed by gh's built-in jq (`gh api --jq`), so jq,
# node and python3 are not required. Pages are fetched one by one instead of with --paginate
# (which stops at page 2 in Claude Code cloud sessions). A comment counts as resolved when it
# has "✅ Issue #N" or "✅ Issue owner/repo#N" anywhere in it.

set -euo pipefail
set -f

US=$'\x1f' nl=$'\n'
RESOLVED_RE='✅ Issue ([^[:space:]]+/[^[:space:]]+)?#[0-9]+'
# In Claude Code cloud sessions the route to GitHub appends this footer to bodies written through
# `gh api`, and moves one already in the body to the end (pitfalls-cloud.md of the issue-start
# skill). `mark` leaves it out wherever it sits when comparing what was sent with what was saved.
CLOUD_FOOTER=$'---\n_Generated by [Claude Code](https://claude.ai/code)_'

die() { echo "knowledge-board: $*" >&2; exit 1; }
# A wrong command line exits 2, so callers can tell it from a failure at run time (exit 1).
misuse() { echo "knowledge-board: $*" >&2; exit 2; }

# grep shortens long lines by characters, which bash counts in bytes under the C locale and would
# cut a Japanese character in half. Switch to a UTF-8 locale when the current one is not.
utf8() { local s='あ'; [[ ${#s} -eq 1 ]]; }
if ! utf8; then
  for l in C.UTF-8 C.utf8 en_US.UTF-8 en_US.utf8; do
    if (export LC_ALL="$l"; utf8) 2>/dev/null; then export LC_ALL="$l"; break; fi
  done
fi
usage() { sed -n '2,/^$/p' "$0" | sed 's/^# \{0,1\}//'; }

cached=0 args=()
for a in "$@"; do
  case "$a" in
    --cached) cached=1 ;;
    -h|--help) usage; exit 0 ;;
    *) args+=("$a") ;;
  esac
done
[[ ${#args[@]} -gt 0 ]] || { echo "knowledge-board: no command" >&2; usage >&2; exit 2; }
cmd=${args[0]}

# The command line is checked before git and gh, so a wrong one exits 2 anywhere.
case "$cmd" in
  open) ;;
  grep) [[ -n "${args[1]:-}" ]] || misuse "usage: grep <pattern>" ;;
  show) [[ -n "${args[1]:-}" ]] || misuse "usage: show <id>" ;;
  mark)
    [[ "${args[1]:-}" =~ ^[0-9]+$ && -n "${args[2]:-}" ]] || misuse 'usage: mark <id> "<marker>"'
    marker=$(printf '%s' "${args[2]}" | sed 's/^[[:space:]]*//; s/[[:space:]]*$//')
    # A marker that `open` cannot recognize (e.g. "✅Issue #12") would leave the insight unresolved.
    if [[ "$marker" == *"$nl"* ]] || ! [[ "$marker" =~ ^$RESOLVED_RE ]]; then
      misuse 'marker must be one line starting with "✅ Issue #<number>" or "✅ Issue <owner>/<repo>#<number>"'
    fi ;;
  *) misuse "unknown command: $cmd (open / grep / show / mark)" ;;
esac

command -v gh >/dev/null 2>&1 || die "gh (GitHub CLI) is required"

rules="$(cd "$(dirname "$0")/.." && pwd)/rules/workflow-feedback.md"
board=""
[[ ! -r "$rules" ]] || board=$(sed -n 's/^- \*\*Issue番号\*\*: #\([0-9][0-9]*\).*/\1/p' "$rules" | head -n 1)
git_dir=$(git rev-parse --git-common-dir 2>/dev/null) || die "run it inside the project's git repository"
git_dir=$(cd "$git_dir" && pwd)
cache_for() { printf '%s/knowledge-board-%s.cache' "$git_dir" "$1"; }

# One line per comment: id, date, URL, work Issue, 重要度, 還元先, resolved, 気づき (60 characters),
# body. The body has CR removed and backslash, newline and tab escaped, for `printf %b`.
# Whitespace is `[\s\p{Zs}]`: gh's jq (gojq) matches only ASCII with `\s`, and a full-width space
# typed with a Japanese IME after "**気づき**：" would otherwise count as an inline value.
comment_jq='
def ls: (.body // "") | gsub("\r"; "") | split("\n");
def strip: sub("^[\\s\\p{Zs}]+"; "") | sub("[\\s\\p{Zs}]+$"; "");
def field($name):
  ls as $l
  | ([range(0; $l | length) | select($l[.] | startswith("**" + $name + "**"))] | first) as $i
  | if $i == null then ""
    else ($l[$i] | sub("^[*][*][^*]+[*][*][:：]?[\\s\\p{Zs}]*"; "") | strip) as $inline
      | if $inline != "" then $inline
        else ([$l[$i + 1:][] | select(strip != "")] | first // "" | strip) end
    end;
def dash: if . == "" then "-" else . end;
.[] | [
  (.id | tostring),
  .created_at[0:10],
  .html_url,
  ([ls[] | select(startswith("## "))] | first // "" | [match("\\[(#[0-9]+)\\]").captures[0].string] | first // "-"),
  (field("重要度") | gsub("~~[^~]*~~[\\s\\p{Zs}]*→?[\\s\\p{Zs}]*"; "") | sub("[（(].*$"; "") | strip | dash),
  (field("還元先") | sub("（↗ 還元済み:[^）]*）"; "（還元済み）") | dash),
  ((.body // "") | test("✅ Issue (\\S+/\\S+)?#[0-9]+") | tostring),
  (field("気づき") | if length > 60 then .[0:60] + "…" else . end),
  ((.body // "") | gsub("\r"; "") | gsub("\\\\"; "\\\\") | gsub("\n"; "\\n") | gsub("\t"; "\\t"))
] | join("\u001f")'

# fetch: every comment of the board, 100 per page, saved to the cache.
fetch() {
  local cache tmp page out count
  cache=$(cache_for "$board")
  # A file of its own: worktrees share the git directory, so two sessions may fetch at once.
  tmp=$(mktemp "$cache.XXXXXX")
  page=1
  while :; do
    out=$(gh api "repos/{owner}/{repo}/issues/$board/comments?per_page=100&page=$page" --jq "$comment_jq") || {
      rm -f "$tmp"; die "gh api failed while reading Issue #$board"
    }
    count=0
    if [[ -n "$out" ]]; then
      printf '%s\n' "$out" >>"$tmp"
      count=$(printf '%s\n' "$out" | wc -l | tr -d ' ')
    fi
    [[ $count -eq 100 ]] || break
    page=$((page + 1))
  done
  mv "$tmp" "$cache"
}

load() {
  [[ -n "$board" ]] || die "no Issue number in $rules (\"- **Issue番号**: #N\" in 知見ボードIssue)"
  if [[ $cached -eq 1 ]]; then
    [[ -f "$(cache_for "$board")" ]] || die "no cached data at $(cache_for "$board"); run without --cached first"
  else
    fetch
  fi
  rows=$(cat "$(cache_for "$board")")
}

each() { # each <function>: calls the function with the fields of every comment
  local id date url work imp up res ins body
  while IFS="$US" read -r id date url work imp up res ins body; do
    [[ -n "$id" ]] || continue
    "$1"
  done <<<"$rows"
}

cmd_open() {
  local total=0 open=0
  row() {
    total=$((total + 1))
    [[ "$res" == true ]] && return
    open=$((open + 1))
    printf '%s  %s  [%s]  %s  %s  %s\n' "$id" "$date" "$work" "$imp" "$up" "$ins"
  }
  each row
  echo "未回収: $open 件 / 全 $total 件"
}

cmd_grep() {
  local pattern=$1 total=0 hits=0 literal=0 rc=0
  # shellcheck disable=SC2319  # the status of [[ =~ ]] itself: 2 means the regex is invalid
  [[ x =~ $pattern ]] || rc=$?
  [[ $rc -ne 2 ]] || literal=1
  shopt -s nocasematch
  row() {
    local text line n=0 shown=0 more=0 t
    total=$((total + 1))
    text=$(printf '%b' "$body")
    while IFS= read -r line; do
      n=$((n + 1))
      if [[ $literal -eq 1 ]]; then [[ $line == *"$pattern"* ]] || continue
      else [[ $line =~ $pattern ]] || continue; fi
      if [[ $shown -eq 0 && $more -eq 0 ]]; then
        hits=$((hits + 1))
        printf '%s  %s  [%s]  %s\n' "$id" "$date" "$work" "$([[ "$res" == true ]] && echo 回収済み || echo 未回収)"
      fi
      if [[ $shown -lt 5 ]]; then
        shown=$((shown + 1))
        t=$(printf '%s' "$line" | sed 's/^[[:space:]]*//; s/[[:space:]]*$//')
        [[ ${#t} -le 160 ]] || t="${t:0:160}…"
        printf '  L%s: %s\n' "$n" "$t"
      else
        more=$((more + 1))
      fi
    done <<<"$text"
    [[ $more -eq 0 ]] || echo "  …他 $more 行"
  }
  each row
  shopt -u nocasematch
  echo "該当: $hits 件 / 全 $total 件"
}

cmd_show() {
  local want=$1 found=0
  row() {
    [[ "$id" == "$want" ]] || return 0
    found=1
    printf '# %s (%s)\n\n%b\n' "$url" "$date" "$body"
  }
  each row
  [[ $found -eq 1 ]] || die "comment $want not found"
}

# comparable <text>: CR removed, the cloud footer taken out wherever it is, each remaining part
# trimmed of surrounding newlines, and the parts joined by a blank line.
comparable() {
  local s=${1//$'\r'/} part out=""
  s=${s//"$CLOUD_FOOTER"/$'\x1e'}
  while IFS= read -r -d $'\x1e' part; do
    part="${part#"${part%%[!$'\n']*}"}"
    part="${part%"${part##*[!$'\n']}"}"
    [[ -n "$part" ]] || continue
    out="${out:+$out$nl$nl}$part"
  done <<<"$s"$'\x1e'
  printf '%s' "$out"
}

# cmd_mark <id> <marker>: both already checked (and the marker trimmed) before git and gh.
cmd_mark() {
  local id=$1 marker=$2 ep before sent after line found="" sent_file after_file cache tmp
  local f1 f2 f3 f4 f5 f6 f8 _
  ep="repos/{owner}/{repo}/issues/comments/$id"
  before=$(gh api "$ep" --jq '.body // ""') || die "gh api failed while reading comment $id"
  while IFS= read -r line; do
    line=$(printf '%s' "$line" | sed 's/^[[:space:]]*//; s/[[:space:]]*$//')
    # Same marker: a re-run after a failed check, so there is nothing to add.
    if [[ "$line" == "$marker" ]]; then echo "already marked: $id"; return 0; fi
    [[ "$line" =~ $RESOLVED_RE ]] && found="${found:+$found / }$line"
  done <<<"${before//$'\r'/}"
  # Another marker: the comment is already resolved, so this is likely the wrong ID or a double promotion.
  [[ -z "$found" ]] || die "comment $id already has a marker ($found); not adding \"$marker\""

  while [[ "$before" == *$'\n' || "$before" == *$'\r' ]]; do before=${before%?}; done
  sent="$before$nl$nl$marker"
  sent_file="$git_dir/knowledge-board-mark-$id.md" after_file="$git_dir/knowledge-board-mark-$id.after.md"
  printf '%s' "$sent" >"$sent_file"
  # From stdin: on Git Bash a path given after "body=@" reaches the native gh.exe unconverted.
  gh api -X PATCH "$ep" -F body=@- <"$sent_file" >/dev/null || die "gh api failed while updating comment $id (sent: $sent_file)"
  after=$(gh api "$ep" --jq '.body // ""') || die "gh api failed while reading comment $id again"
  if [[ "$(comparable "$after")" != "$(comparable "$sent")" ]]; then
    printf '%s' "$after" >"$after_file"
    die "comment $id does not match what was sent; diff $sent_file $after_file"
  fi
  rm -f "$sent_file"

  # Keep `open --cached` from listing the insight as unresolved after it is marked.
  if [[ -n "$board" && -f "$(cache_for "$board")" ]]; then
    cache=$(cache_for "$board")
    tmp=$(mktemp "$cache.XXXXXX")
    after=${after//$'\r'/}; after=${after//\\/\\\\}; after=${after//$'\n'/\\n}; after=${after//$'\t'/\\t}
    while IFS= read -r line; do
      if [[ "${line%%"$US"*}" == "$id" ]]; then
        IFS="$US" read -r f1 f2 f3 f4 f5 f6 _ f8 _ <<<"$line"
        line="$f1$US$f2$US$f3$US$f4$US$f5$US${f6}${US}true$US$f8$US$after"
      fi
      printf '%s\n' "$line"
    done <"$cache" >"$tmp"
    mv "$tmp" "$cache"
  fi
  echo "marked: $id"
}

case "$cmd" in
  open) load; cmd_open ;;
  grep) load; cmd_grep "${args[1]}" ;;
  show) load; cmd_show "${args[1]}" ;;
  mark) cmd_mark "${args[1]}" "$marker" ;;
esac
